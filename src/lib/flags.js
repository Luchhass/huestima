const displayNames = {
  en: new Intl.DisplayNames(["en"], { type: "region" }),
  tr: new Intl.DisplayNames(["tr"], { type: "region" }),
};

function buildFlagLabels(item) {
  const regionCode = FLAG_REGION_CODES[item.id];

  if (!regionCode) {
    return { en: item.label, tr: item.label };
  }

  return {
    en: displayNames.en.of(regionCode) || item.label,
    tr: displayNames.tr.of(regionCode) || item.label,
  };
}

function flag(item) {
  const assetRoot = "/game-modes/flag/generated";
  const scenePath = `${assetRoot}/${item.id}-scene.webp`;
  const originalScenePath = `${assetRoot}/${item.id}-original.webp`;
  const maskPath = `${assetRoot}/${item.id}-scene-mask.png`;
  const mainLayerPath = `${assetRoot}/${item.id}-main-layer.png`;

  return {
    id: item.id,
    label: item.label,
    labels: buildFlagLabels(item),
    paintLabel: "flag",
    originalScenePath,
    baseScenePath: scenePath,
    scenePath,
    imagePath: scenePath,
    maskPath,
    assetPath: scenePath,
    paint: item.paint,
    difficulty: getFlagDifficulty(item.id),
    layers: [
      {
        id: "main",
        label: "flag",
        sourcePath: mainLayerPath,
        maskPath,
        base: item.paint,
      },
    ],
  };
}

export const FLAG_OPTIONS = FLAG_ITEMS.map(flag);
export { FLAG_DIFFICULTY_IDS, FLAG_DIFFICULTY_OPTIONS, getFlagsForDifficulty };

export const DEFAULT_FLAG_ID = FLAG_OPTIONS[0]?.id || null;

export function getFlagOption(flagId) {
  return (
    FLAG_OPTIONS.find((flagOption) => flagOption.id === flagId) ||
    FLAG_OPTIONS.find((flagOption) => flagOption.id === DEFAULT_FLAG_ID) ||
    null
  );
}
