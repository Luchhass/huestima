import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { POKEMON_ITEMS } from "../shared/pokemonCatalog.mjs";
import {
  buildTransparentArtworkLayers,
  writeTransparentArtworkScene,
} from "./lib/visual-scene-pipeline.mjs";

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_DIR = path.resolve(PROJECT_ROOT, "public", "game-modes", "pokemon", "generated");
const PAINT_CATALOG_PATH = path.resolve(PROJECT_ROOT, "shared", "pokemonPaintCatalog.mjs");

async function main() {
  await fs.mkdir(OUTPUT_DIR, { recursive: true });
  const paintCatalog = {};

  for (const pokemon of POKEMON_ITEMS) {
    const sourcePath = path.resolve(PROJECT_ROOT, "public", decodeURIComponent(pokemon.imagePath.slice(1)));
    const layers = await buildTransparentArtworkLayers(sourcePath, {
      width: 1920,
      height: 1080,
      artworkWidth: 1420,
      artworkHeight: 780,
    });
    await writeTransparentArtworkScene({ layers, outputDir: OUTPUT_DIR, id: pokemon.id });
    paintCatalog[pokemon.id] = layers.paint;
    console.log(`generated ${pokemon.id} ${pokemon.name} (${layers.raw.width}x${layers.raw.height})`);
  }

  await fs.writeFile(
    PAINT_CATALOG_PATH,
    `// Generated by scripts/build-pokemon-scenes.mjs from each Pokémon artwork.\n` +
      `// Values anchor hue, saturation, and value changes in the shared renderer.\n` +
      `export const POKEMON_PAINT = ${JSON.stringify(paintCatalog, null, 2)};\n`,
  );
  console.log(`generated ${POKEMON_ITEMS.length} Pokémon render packs`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
