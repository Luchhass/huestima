import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TEAM_ITEMS } from "../shared/brandCatalog.mjs";
import { BRAND_PAINT } from "../shared/visualPaintCatalog.mjs";
import {
  buildTransparentArtworkLayers,
  writeTransparentArtworkScene,
} from "./lib/visual-scene-pipeline.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "public", "game-modes", "team", "team-logos");
const outputDir = path.join(root, "public", "game-modes", "team", "generated");
const catalogPath = path.join(root, "shared", "visualPaintCatalog.mjs");

await fs.mkdir(outputDir, { recursive: true });
const entries = await Promise.all(
  TEAM_ITEMS.map(async (team) => {
    const layers = await buildTransparentArtworkLayers(path.join(sourceDir, team.assetFile));
    await writeTransparentArtworkScene({ layers, outputDir, id: team.id });
    return [team.id, layers.paint];
  }),
);

const teamPaint = Object.fromEntries(entries);
await fs.writeFile(
  catalogPath,
  `// Generated by the visual scene build scripts. Values are measured from the\n` +
    `// original artwork and are the neutral anchor for the shared delta renderer.\n` +
    `export const BRAND_PAINT = ${JSON.stringify(BRAND_PAINT, null, 2)};\n` +
    `export const TEAM_PAINT = ${JSON.stringify(teamPaint, null, 2)};\n`,
);

console.log(`Built ${TEAM_ITEMS.length} team scenes with measured paint anchors.`);
