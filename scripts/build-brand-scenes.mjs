import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BRAND_ITEMS } from "../shared/brandCatalog.mjs";
import { TEAM_PAINT } from "../shared/visualPaintCatalog.mjs";
import {
  buildTransparentArtworkLayers,
  writeTransparentArtworkScene,
} from "./lib/visual-scene-pipeline.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "public", "game-modes", "brand", "brand-logos");
const outputDir = path.join(root, "public", "game-modes", "brand", "generated");
const catalogPath = path.join(root, "shared", "visualPaintCatalog.mjs");

await fs.mkdir(outputDir, { recursive: true });
const entries = await Promise.all(
  BRAND_ITEMS.map(async (brand) => {
    const layers = await buildTransparentArtworkLayers(path.join(sourceDir, brand.assetFile));
    await writeTransparentArtworkScene({ layers, outputDir, id: brand.id });
    return [brand.id, layers.paint];
  }),
);

const brandPaint = Object.fromEntries(entries);
await fs.writeFile(
  catalogPath,
  `// Generated by the visual scene build scripts. Values are measured from the\n` +
    `// original artwork and are the neutral anchor for the shared delta renderer.\n` +
    `export const BRAND_PAINT = ${JSON.stringify(brandPaint, null, 2)};\n` +
    `export const TEAM_PAINT = ${JSON.stringify(TEAM_PAINT, null, 2)};\n`,
);

console.log(`Built ${BRAND_ITEMS.length} brand scenes with measured paint anchors.`);
