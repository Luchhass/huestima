function withGeneratedAssets(item) {
  const generatedRoot = `${GENERATED_ROOT}/${item.id}`;
  const paint = POKEMON_PAINT[item.id] || { h: 0, s: 0, v: 100 };
  const scenePath = `${generatedRoot}-scene.webp`;
  const originalScenePath = `${generatedRoot}-original.webp`;
  const maskPath = `${generatedRoot}-scene-mask.png`;

  return {
    ...item,
    paint,
    scenePath,
    baseScenePath: scenePath,
    originalScenePath,
    maskPath,
    assetPath: scenePath,
    layers: [{ id: "main", maskPath, base: paint }],
  };
}

export const POKEMON_ITEMS = SOURCE_POKEMON_ITEMS.map(withGeneratedAssets);

export function getPokemonItem(id) {
  return POKEMON_ITEMS.find((pokemon) => pokemon.id === id) || POKEMON_ITEMS[0];
}
